"""Generate src/engine/metrics.js from the TTF files in public/assets/.

The mod renders text with Skia using `setSubpixel(true)` + `setMetricsLinear(true)`,
i.e. unhinted linear metrics.  That means:

    measureTextWidth(text) == sum(advanceUnits(c) * size / unitsPerEm)
    getHeight()            == (lineGap - ascent - descent) / 2 * size / unitsPerEm

with ascent/descent/lineGap taken from `hhea` (none of the shipped fonts set the
OS/2 USE_TYPO_METRICS bit, so Skia uses hhea metrics).

We extract those tables here so the browser does not have to rely on its own font
metric guesses, which makes the web port bit-for-bit deterministic.
"""

import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "assets"
TARGET = ROOT / "src" / "engine" / "metrics.js"

FONTS = {
    "SH_LIGHT": "SourceHanSansSC-Light.ttf",
    "SH_REGULAR": "SourceHanSansSC-Regular.ttf",
    "SH_HEAVY": "SourceHanSansSC-Heavy.ttf",
    "SH_NORMAL": "SourceHanSansSC-Normal.ttf",
    "SH_BOLD": "SourceHanSansSC-Bold.ttf",
    "RADIKAL_REGULAR": "Radikal-Regular.ttf",
}


def tables(data):
    count = struct.unpack(">H", data[4:6])[0]
    out = {}
    for i in range(count):
        off = 12 + i * 16
        tag = data[off : off + 4].decode("latin1")
        start, length = struct.unpack(">II", data[off + 8 : off + 16])
        out[tag] = (start, length)
    return out


def cmap_map(data, cmap_off):
    count = struct.unpack(">H", data[cmap_off + 2 : cmap_off + 4])[0]
    best = None
    for i in range(count):
        _pid, _eid, sub_off = struct.unpack(
            ">HHI", data[cmap_off + 4 + i * 8 : cmap_off + 12 + i * 8]
        )
        sub = cmap_off + sub_off
        fmt = struct.unpack(">H", data[sub : sub + 2])[0]
        if fmt == 12:
            best = sub
        elif fmt == 4 and best is None:
            best = sub
    if best is None:
        return {}
    fmt = struct.unpack(">H", data[best : best + 2])[0]
    mapping = {}
    if fmt == 4:
        seg_x2 = struct.unpack(">H", data[best + 6 : best + 8])[0]
        seg = seg_x2 // 2
        ends = struct.unpack(">%dH" % seg, data[best + 14 : best + 14 + seg_x2])
        starts = struct.unpack(">%dH" % seg, data[best + 16 + seg_x2 : best + 16 + 2 * seg_x2])
        deltas = struct.unpack(">%dh" % seg, data[best + 16 + 2 * seg_x2 : best + 16 + 3 * seg_x2])
        range_off_base = best + 16 + 3 * seg_x2
        range_offsets = struct.unpack(
            ">%dH" % seg, data[range_off_base : range_off_base + seg_x2]
        )
        for i in range(seg):
            s, e = starts[i], ends[i]
            if s == 0xFFFF:
                continue
            for c in range(s, min(e, 0xFFFE) + 1):
                if range_offsets[i] == 0:
                    gid = (c + deltas[i]) & 0xFFFF
                else:
                    addr = range_off_base + i * 2 + range_offsets[i] + (c - s) * 2
                    gid = struct.unpack(">H", data[addr : addr + 2])[0]
                    if gid:
                        gid = (gid + deltas[i]) & 0xFFFF
                if gid:
                    mapping[c] = gid
    elif fmt == 12:
        groups = struct.unpack(">I", data[best + 12 : best + 16])[0]
        for i in range(groups):
            s, e, g = struct.unpack(
                ">III", data[best + 16 + i * 12 : best + 28 + i * 12]
            )
            for c in range(s, e + 1):
                mapping[c] = g + (c - s)
    return mapping


def hmtx_advances(data, hhea_off, hmtx_off, num_glyphs):
    num_h = struct.unpack(">H", data[hhea_off + 34 : hhea_off + 36])[0]
    advances = []
    last = 0
    for i in range(num_glyphs):
        if i < num_h:
            last = struct.unpack(">H", data[hmtx_off + i * 4 : hmtx_off + i * 4 + 2])[0]
        advances.append(last)
    return advances


def main():
    out = {}
    for name, filename in FONTS.items():
        path = SRC / filename
        data = path.read_bytes()
        t = tables(data)
        head_off = t["head"][0]
        upem = struct.unpack(">H", data[head_off + 18 : head_off + 20])[0]
        hhea_off = t["hhea"][0]
        ascent, descent, line_gap = struct.unpack(">hhh", data[hhea_off + 4 : hhea_off + 10])
        num_glyphs = struct.unpack(">H", data[t["maxp"][0] + 4 : t["maxp"][0] + 6])[0]
        advances = hmtx_advances(data, hhea_off, t["hmtx"][0], num_glyphs)
        cmap = cmap_map(data, t["cmap"][0])

        table = {}
        for code in list(range(32, 127)) + [160, 173]:
            gid = cmap.get(code, 0)
            table[code] = advances[gid] if gid < len(advances) else 0

        out[name] = {
            "upem": upem,
            "ascent": ascent,
            "descent": descent,
            "lineGap": line_gap,
            "advances": table,
        }

    lines = [
        "// AUTO-GENERATED by tools/gen-font-metrics.py -- do not edit by hand.",
        "// Values are the raw hhea/hmtx/cmap data of the TTF files shipped in",
        "// public/assets.",
        "",
        "export const FONT_METRICS = {",
    ]
    for name, info in out.items():
        lines.append("  %s: {" % name)
        lines.append("    upem: %d," % info["upem"])
        lines.append("    ascent: %d," % info["ascent"])
        lines.append("    descent: %d," % info["descent"])
        lines.append("    lineGap: %d," % info["lineGap"])
        lines.append("    advances: {")
        items = ["%d: %d" % (c, a) for c, a in sorted(info["advances"].items())]
        for i in range(0, len(items), 8):
            lines.append("      " + ", ".join(items[i : i + 8]) + ",")
        lines.append("    },")
        lines.append("  },")
    lines.append("};")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", TARGET.relative_to(ROOT))


if __name__ == "__main__":
    main()
